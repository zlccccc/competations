void dfs(int x,int y){
	int i,j,k,nextx,nexty;
	bool ff;
	if (flag) return;
	while (map[x][y]!='.') {
		y++;
		if (y>x) {y=1;x++;}
		if (x==maxn+1) {
			for (i=1;i<=maxn;i++)for (j=1;j<=i;j++)ans[i][j]=map[i][j];
			flag=true;
			return;
		}
	}
	for (i=0;i<12;i++) 
 		if (!used[i])
			for (j=0;j<num[i][0];j++){
				ff=true;
				for (k=0;k<num[i][1];k++){
					nextx=x+a[i][j][k][0];
					nexty=y+a[i][j][k][1];

					if (!(nextx>0 && nextx<11 && nexty>0 && nexty<11 && nextx>=nexty)||
						(map[x+a[i][j][k][0]][y+a[i][j][k][1]]!='.')){
						ff=false;
						break;
					}
				}
				if (ff) {
					used[i]=true;
					for (k=0;k<num[i][1];k++)map[x+a[i][j][k][0]][y+a[i][j][k][1]]='A'+i;
					dfs(x,y);
					for (k=0;k<num[i][1];k++)map[x+a[i][j][k][0]][y+a[i][j][k][1]]='.';
					used[i]=false;
				}
			}
}

